"""Generate Flutter prototype tokens/font from the canonical local sources."""
import argparse
import io
import json
from pathlib import Path

from fontTools.ttLib import TTFont
from android_brand import generate_android_brand

ROOT = Path(__file__).resolve().parents[3]
MOBILE = ROOT / "apps/mobile"


def generate():
    tokens = json.loads((ROOT / "packages/design-tokens/preview.json").read_text(encoding="utf-8"))
    effects = json.loads((ROOT / "packages/design-tokens/mobile-effects.json").read_text(encoding="utf-8"))
    symbol = json.loads((ROOT / "docs/GUI/identidad/guia/modelo.json").read_text(encoding="utf-8"))["symbol"]
    # QMark paints this canonical circle/tail geometry. Fail if it changes.
    assert symbol == "M50 12a34 34 0 1 0 0 68 34 34 0 1 0 0-68 M62 66l24 22"
    lines = ["// Generated by tool/generate_prototype_assets.py. Do not edit.",
             "import 'package:flutter/material.dart';", "", "abstract final class MobileTokens {"]
    for name, value in tokens["colors"].items():
        lines.append(f"  static const {name} = Color(0xFF{value[1:]});")
    for theme, roles in tokens["themes"].items():
        lines.append(f"  static const {theme} = <String, Color>{{")
        lines.extend(f"    '{role}': {color}," for role, color in roles.items())
        lines.append("  };")
    geometry = tokens["prototypeIslands"]
    for key in ["margin", "gap", "headerHeight", "navigationHeight", "navigationRadius", "targetHeight"]:
        lines.append(f"  static const {key} = {float(geometry[key])};")
    lines += [f"  static const surfaceRadius = {float(effects['surfaceRadius'])};",
              f"  static const minimumSigma = {float(effects['glass']['minimumSigma'])};",
              f"  static const maximumSigma = {float(effects['glass']['maximumSigma'])};",
              f"  static const defaultIntensity = {effects['glass']['defaultIntensity']};"]
    for name in ["lightOpacity", "darkOpacity", "highlightAlpha", "backdropAlpha"]:
        lines.append(f"  static const {name} = {effects['glass'][name]};")
    for name, value in effects["motion"].items():
        lines.append(f"  static const {name} = Duration(milliseconds: {value});")
    for name, value in effects["launch"].items():
        lines.append(f"  static const {name} = {float(value)};")
    lines += ["}", ""]
    font = TTFont(ROOT / "docs/GUI/assets/inter.woff2", recalcTimestamp=False)
    font.flavor = None
    stream = io.BytesIO()
    font.save(stream)
    return {
        **generate_android_brand(MOBILE, tokens, symbol),
        MOBILE / "lib/prototype/generated_tokens.dart": "\n".join(lines).encode(),
        MOBILE / "assets/prototype/Inter.ttf": stream.getvalue(),
        MOBILE / "assets/prototype/inter-license.txt": (ROOT / "docs/GUI/assets/inter-license.txt").read_bytes(),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generate().items():
        if args.check:
            actual = path.read_bytes() if path.exists() else b""
            if path.suffix not in {".ttf", ".png"}:
                actual, expected = actual.replace(b"\r\n", b"\n"), expected.replace(b"\r\n", b"\n")
            assert actual == expected, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    print("Canonical Flutter prototype assets verified." if args.check else "Flutter prototype assets generated.")
